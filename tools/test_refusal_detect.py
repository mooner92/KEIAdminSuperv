def main() -> int:
    bad = 0
    for name, text, want in CASES:
        got = is_refusal(text)
        ok = got == want
        bad += not ok
        print(f"  {'✅' if ok else '❌'} {name}: is_refusal={got} (기대 {want})")
    print(f"\n{'🎉 전 케이스 통과' if not bad else f'⚠ {bad}건 실패'} ({len(CASES)}건)")
    return 0 if not bad else 1


