PARA_MAX_OVERLAP = float(os.environ.get("DAILY_EVAL_PARA_MAXOV", "0.55"))


def paraphrase(llm_json_fn, q: str, src: str, rng=None, tries: int = 2) -> tuple:
    """문서어 질문 → 일상어 질문. 반환 (질문 or None, 사유).
    게이트 3중: ⓐ 기존 결함 사전 ⓑ 원문 어휘 겹침 상한(PARA_MAX_OVERLAP) ⓒ 뜻 보존 심판.
    ⛔ 실패는 '폐기'다 — 억지로 통과시키면 갭 수치가 거짓이 된다(문항 하나 잃는 편이 싸다)."""
    r0 = rng or random
    last = "미생성"
    for _ in range(max(1, tries)):
        r = llm_json_fn([{"role": "system", "content": PARAPHRASE_SYS},
                         {"role": "user", "content":
                          f"[다시 쓰는 사람: {r0.choice(PERSONAS)} · 말투: {r0.choice(STYLES)}]\n질문: {q}"}],
                        temperature=0.8, max_tokens=140)
        p = re.sub(r"\s+", " ", str((r or {}).get("질문", ""))).strip()
        if not p:
            last = "패러프레이저 빈 출력"
            continue
        d = question_defects(p)                       # ⓐ 사람 같은 문장인지는 기존 사전 그대로
        if d:
            last = f"결함 {','.join(d)}"
            continue
        # ⓐ' 자족성 — 원 출제에만 걸려 있던 게이트다. 패러프레이즈는 맥락을 줄이는 작업이라
        #    오히려 여기서 더 잘 깨진다(2026-08-03 실측: "상사 출장 가기 전에 저는 안 되는
        #    거예요?" — 무엇을 묻는지 사라진 채 채점까지 갔다).
        from daily_common import is_self_contained  # 지연 import — 순환 방지
        if not is_self_contained(p):
            last = "자족성 실패(지시어·맥락 의존)"
            continue
        ov = doc_overlap(p, src)                      # ⓑ 문서 어휘가 남았으면 패러프레이즈 실패
        if ov > PARA_MAX_OVERLAP:
            last = f"어휘겹침 {ov:.2f} — 문서어 잔존"
            continue
        e = llm_json_fn([{"role": "system", "content": EQUIV_SYS},   # ⓒ 뜻 보존
                         {"role": "user", "content": f"질문A: {q}\n질문B: {p}"}],
                        temperature=0.0, max_tokens=100)
        if e and not bool(e.get("같음", True)):
            last = f"뜻 달라짐 — {str(e.get('사유',''))[:60]}"
            continue
        return p, f"겹침 {ov:.2f}"
    return None, last
