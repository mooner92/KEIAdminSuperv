REFEREE_SYS = """너는 사내 규정 챗봇의 시험 문항 검수자다. 문항 하나가 주어진다.
판단할 것은 단 두 가지다:
1. 사람같음(1~5): 실제 직원이 업무 중에 챗봇 입력창에 **이렇게 칠 것 같은가**.
   5=완전히 자연스러움 · 3=어색하지만 가능 · 1=문서에서 오려낸 문장(사람은 이렇게 안 씀)
   깎는 신호: 문서 용어를 그대로 읽음("~에 명시된 항목은"), 관리자 시점("표는 어떻게 작성"),
   지나치게 완결된 법조문 어투, 화면 명세 질문("어떤 값으로 표시").
2. 혼자성립(true/false): 원문 없이 질문만 읽어도 무엇을 묻는지 완전한가.
JSON만 출력: {"사람같음": <1-5>, "혼자성립": <true|false>, "사유": "<한 줄>"}"""


def referee(llm_json_fn, q: str) -> tuple:
    """(통과?, 사유). 사람같음 4점 미만 또는 혼자성립 실패면 폐기.
    LLM 호출 실패는 통과로 둔다 — 검수자가 죽었다고 출제가 멈추면 안 된다(②가 이미 걸렀다)."""
    r = llm_json_fn([{"role": "system", "content": REFEREE_SYS},
                     {"role": "user", "content": f"문항: {q}"}], temperature=0.0, max_tokens=120)
    if not r:
        return True, "검수자 무응답(통과)"
    try:
        score = int(r.get("사람같음", 5))
        standalone = bool(r.get("혼자성립", True))
    except (TypeError, ValueError):
        return True, "검수자 형식 오류(통과)"
    why = str(r.get("사유", ""))[:80]
    if score < 4:
        return False, f"사람같음 {score}점 — {why}"
    if not standalone:
        return False, f"혼자성립 실패 — {why}"
    return True, ""


