# 내용어 추출 — 조사를 떼고 남는 2글자 이상 한글/영숫자 덩어리.
# 형태소 분석기를 안 쓰는 이유: 결정적·무의존성이어야 테스트가 고정되고 크론이 안 죽는다.
# ⚠ 의문·서술 토큰을 **접두 일치로** 뺀 것이 이 지표의 핵심(2026-08-02 보정): 처음엔 정확일치
#   불용어만 뒀는데 "중복게재란 무엇입니까?"가 겹침 0.00으로 나왔다 — '무엇입니까'가 활용형이라
#   불용어에 안 걸려 분모를 채우고, '중복게재란'은 어미가 붙어 원문과 안 맞았다. 지표가 틀리면
#   임계값도 거짓이 된다.
_JOSA = ("으로써", "으로서", "이라도", "에서는", "에게서", "으로는", "까지는", "부터는",
         "에서", "에게", "으로", "라도", "부터", "까지", "보다", "처럼", "마다", "이나",
         "은", "는", "이", "가", "을", "를", "의", "에", "도", "만", "과", "와", "로", "나")
_STOP_PREFIX = ("무엇", "어떻", "어떤", "어느", "언제", "얼마", "누가", "누구", "어디", "왜", "몇",
                "되나", "되는", "되어", "하나", "하는", "해야", "하면", "한가", "인가", "인지",
                "있나", "있는", "없나", "없는", "가능", "필요", "알려", "궁금", "알고", "싶",
                "주세", "합니", "입니", "습니", "건가", "건지", "드리", "봐도", "되죠", "맞나", "맞는")


def content_words(s: str) -> set:
    """질문/원문의 내용어 집합. 조사 제거 + 의문·서술 토큰 제외 — 어휘 겹침 측정의 단위."""
    out = set()
    for tok in re.findall(r"[가-힣A-Za-z0-9]+", s or ""):
        for j in _JOSA:                      # 긴 조사부터 1회만
            if len(tok) > len(j) + 1 and tok.endswith(j):
                tok = tok[: -len(j)]
                break
        if len(tok) >= 2 and not any(tok.startswith(p) for p in _STOP_PREFIX):
            out.add(tok)
    return out


def doc_overlap(q: str, src: str) -> float:
    """질문 내용어 중 **원문에 그대로 있는** 비율(0~1). 문서어 문항은 높고 일상어는 낮아야 한다.
    끝 1자는 활용 여지로 떼고 대조한다('관리대장에는'→'관리대장'→'관리대'로 탐색).
    ⚠ 방향이 동어반복 필터와 반대다: 저기선 골든 되읽기를 막고, 여기선 문서 어휘 잔존을 막는다."""
    cw = content_words(q)
    if not cw:
        return 0.0
    srcn = re.sub(r"\s+", "", src or "")
    return sum(1 for w in cw if (w if len(w) <= 2 else w[:-1]) in srcn) / len(cw)


