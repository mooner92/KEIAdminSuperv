# ───────────────────── ② 결정적 결함 사전 ─────────────────────
# 코드 → 패턴. 전부 2026-07-31 실측 결함에서 역산 — 각 항목이 실제 사고 하나씩이다.
_ENDING_OK = re.compile(r"(요|죠)\s*[?.…]?$")          # 해요체 종결(물음표 유무 허용)
_EXAM_TONE = re.compile(r"(하는가|는가|은가|인가|한가|무엇인가|어떠한가)\s*\?*$|하시오|서술하라|설명하라")
_ORPHAN_JOSA = re.compile(r"(^|\s)[을를](\s|$)")        # 어절로 홀로 남은 목적격 조사 = 문장 파손
_DOC_FRAGMENT = re.compile(
    r"어떤 값으로 표시|필드에 저장|레이어|호출되(는가|나요)|증감\s*표시|표에서|별표에서|목차|컬럼|"
    r"현황에 포함되어야 하는 항목")
_META_ARTICLE = re.compile(r"제\s*\d+\s*조는|언제부터 시행|시행일이? 언제|부칙")
_MID_DEICTIC = re.compile(r"해당 (표|별표|화면|항목|서식)|본 (규정|지침|편람)|위 (표|규정|조항)")
_LONG_QUOTE = re.compile(r"[\"“'‘][^\"”'’]{30,}[\"”'’]")
# 출제 지시문 누출 — 출제 LLM이 **자기가 받은 지시를 그대로 뱉은** 것을 게이트가 통과시켰다.
# 실측(은행 전수, 2026-08-15): "탕비실 커피머리 보습을 위한 자연스러운 질문 1개 만들어주세요."
#   이 문장은 '요'로 끝나 종결어미 게이트를 통과했고, 지시어·한자·파편도 없어 전부 빠져나갔다.
#   시험 문제 자리에 출제 지시문이 앉으면 서비스가 무엇을 하든 오답이다(점수 오염의 순수 사례).
# ⚠ 패턴은 **메타 어휘가 있을 때만** 문다 — "알려주세요"(정상 132건)를 죽이면 안 되므로
#   '만들어/생성해 주세요'만 잡고 '알려/설명해 주세요'는 건드리지 않는다(은행 전수 오탐 0 확인).
_PROMPT_LEAK = re.compile(
    r"(?:질문|문항)\s*\d+\s*개"                    # "질문 1개"
    r"|(?:질문|문항)을?\s*(?:만들|생성|작성)"         # "질문을 만들어"
    r"|자연스러운\s*(?:질문|문항)"                   # "자연스러운 질문"
    r"|만들어\s*주세요|생성해\s*주세요"               # 출제 명령형(알려주세요는 제외)
    r"|JSON"                                      # 출력 형식 지시가 새어나온 것
    r"|다음\s*주제로|^\s*주제\s*[:：]"               # 주제 주입문
    r"|출력하라|출력하세요")
# 한자 혼입 = 생성 모델의 코드 스위칭(2026-08-03 실측 12/661, 특히 일상어 4.2%):
#   "예산决算 같은 거", "몇 年工作经历", "뭐都有哪些까요" — 직원은 이렇게 쓰지 않는다.
# ⚠ 단 규정 원문은 한글(漢字) 병기를 쓴다("심의가 부(否)라면") — 괄호 안 한자는 정상 인용이므로
#   괄호쌍을 지운 뒤 남는 한자만 결함으로 본다(정상 문항을 죽이지 않기 위한 예외).
_HANJA = re.compile(r"[一-鿿]")
# 부칙(시행일·경과조치) 골든 — 업무 질문의 답이 될 수 없다.
#   실측 리프트(은행 7,014문항 · 채점 8,400여 이벤트, 2026-08-17):
#     · 부칙 골든 **전체**  : 21문항/21출제 → 폐기율 19.0% (기저 4.5% · ×4.3 · Fisher p=0.013)
#     · 그중 질문이 **시점**을 묻는 것: 폐기 8.3% · 미정답 0/11 — 부칙이 정확히 그 답이다.
#       ("직인규정이 오늘부터 적용될까요?" / "이 규정은 2023.11.27부터 시행한다.")
#     · 질문이 시점을 **안 묻는 것**  : 폐기 3 · 판정불가 1 · 오답 1 · **정답 0**
#   → 통째로 막으면 정상 문항 12건이 죽는다. 게이트는 '부칙 골든 ∧ 시점 질문 아님'으로 좁혔다
#     (정답 문항 collateral 0). 실물: 질문 "복귀했는데 서류가 반려됐는데 왜 안 되나요?" /
#     골든 "이 규정 시행 전에 처리된 사항에 대하여는 이 규정에 의한 것으로 본다." — 부칙 경과조치는
#     '왜 반려됐나'의 답이 아니다. 무엇을 답해도 대조가 안 되므로 채점기가 폐기로 돌린다.
#   ⚠ 질문 텍스트의 "부칙"은 _META_ARTICLE이 이미 문다. 여기는 **골든 쪽**이 부칙인 경우다.
_GOLDEN_BUCHIK = re.compile(
    r"이 (규정|규칙|지침|기준|요령|세칙)(은|는)\s*.{0,30}시행한다"   # 시행일 조항
    r"|시행 전에 처리된"                                          # 경과조치
    r"|종전의 (규정|규칙)에 (따라|의하여|의한)")
# 시점을 묻는 질문 = 부칙이 정당한 정답인 경우(위 예외). 어미가 아니라 **시점 어휘**로 판별한다.
_Q_TIMEPOINT = re.compile(
    r"시행|적용|효력|발효|종전|개정 ?전"
    r"|언제부터|오늘부터|내일부터|부터 시작|부터 쓸|부터 신청|부터 사용|부터 유효"
    r"|(과거|이전)에 (이미 )?처리")


def _hanja_outside_parens(q: str) -> bool:
    return bool(_HANJA.search(re.sub(r"[(（][^)）]*[)）]", "", q)))


def question_defects(q: str, golden: str = "", qtype: str = "") -> list:
    """질문의 결함 코드 목록(빈 리스트 = 통과). 각 코드는 실측 사고 1건에 대응 — 테스트가 고정한다."""
    q = re.sub(r"\s+", " ", (q or "")).strip()
    out = []
    if _PROMPT_LEAK.search(q):
        out.append("출제지시누출")     # 시험 문제 자리에 출제 지시문이 앉은 것 — 최우선 폐기
    if len(q) < 8 or len(q) > 90:
        out.append("길이")
    if _EXAM_TONE.search(q):
        out.append("시험지말투")
    elif not _ENDING_OK.search(q):
        out.append("종결어미")           # 해요체가 아니면 챗봇에 치는 말이 아니다
    if _ORPHAN_JOSA.search(q):
        out.append("문장파손")
    if _DOC_FRAGMENT.search(q):
        out.append("문서파편")
    if _META_ARTICLE.search(q):
        out.append("메타질문")
    if _MID_DEICTIC.search(q):
        out.append("지시어")
    if _LONG_QUOTE.search(q):
        out.append("인용과다")
    if _hanja_outside_parens(q):
        out.append("한자혼입")
    # 3중 복합절 — 사람도 가끔 길게 묻지만 단문 유형(값·절차·조건)에서 '~이며/~되며' 연쇄는 출제 냄새
    if qtype in ("값형", "절차형", "조건형") and len(re.findall(r"(이며|되며|하며)", q)) >= 2:
        out.append("복합절과다")
    # 동어반복 — 질문이 골든을 그대로 되읽으면 검색 없이도 맞는 무의미 문항.
    # ⚠ 척도는 자카드(합집합)가 아니라 **질문 쪽 포함률**: 되읽기의 정의가 '질문 그램의
    #   대부분이 골든에서 왔다'이므로 분모는 질문이다(자카드는 골든이 길수록 희석돼 놓친다).
    if golden:
        qn, gn = q.replace(" ", ""), golden.replace(" ", "")
        qg = {qn[i:i + 2] for i in range(len(qn) - 1)}
        gg = {gn[i:i + 2] for i in range(len(gn) - 1)}
        if qg and gg and len(qg & gg) / len(qg) > 0.7:
            out.append("동어반복")
    # 부칙 골든인데 질문이 시점을 안 묻는다 = 답이 될 수 없는 문항(위 _GOLDEN_BUCHIK 리프트 주석)
    if golden and _GOLDEN_BUCHIK.search(golden) and not _Q_TIMEPOINT.search(q):
        out.append("부칙골든")
    return out


